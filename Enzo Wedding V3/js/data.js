/** Looks up the Rp/pcs rate for a given base order qty + foil location
 * ('sedang' | 'besar' | 'isi'). Qty above 1000 reuses the 900–1000 rate
 * (no pricelist data beyond 1000 yet); below the lowest listed qty falls
 * back to the 100pcs rate. */
function foilRate(qty, location) {
  const exact = FOIL_TIERS.find((t) => t.qty === qty);
  if (exact) return exact[location];
  if (qty > 1000) return FOIL_TIERS[FOIL_TIERS.length - 1][location];
  const sorted = [...FOIL_TIERS].sort((a, b) => a.qty - b.qty);
  const above = sorted.find((t) => t.qty > qty);
  return above ? above[location] : sorted[sorted.length - 1][location];
}

